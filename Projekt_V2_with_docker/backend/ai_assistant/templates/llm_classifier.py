"""
LLM-классификатор намерений.

Определяет, подходит ли запрос под один из шаблонных ответов,
или должен уйти в полный LLM pipeline.

Почему не regex/семантика:
  - "я попал в дтп" → regex ловил паттерн "привет" через другие совпадения
  - "помогите заполнить европротокол" → семантика путала с "что такое европротокол"
  LLM понимает намерение, а не просто слова.
"""

from __future__ import annotations

import json
import re
from typing import Optional

from gigachat import GigaChat

# Описания категорий — чёткие границы, что входит, что нет
_CATEGORIES = {
    "greeting": (
        "Пользователь просто приветствует: 'привет', 'добрый день', 'здравствуйте'. "
        "НЕ входит: любое упоминание ДТП, аварии, страховки, даже если есть слово 'привет'."
    ),
    "what_is_europrotocol": (
        "Пользователь хочет узнать, ЧТО такое европротокол — определение, суть, принцип. "
        "НЕ входит: просьба помочь заполнить, оформить, инструкция по заполнению."
    ),
    "payment_limits": (
        "Вопрос о конкретных суммах выплат по ОСАГО или европротоколу: "
        "сколько заплатят, лимиты, 400/200/100 тысяч."
    ),
    "deadlines": (
        "Вопрос о сроках: когда подавать документы, сколько дней на уведомление страховой, "
        "когда можно ремонтировать, 5 рабочих дней, 15 календарных."
    ),
    "emergency_numbers": (
        "Запрашивает телефоны экстренных служб: 112, 102, 103, 101, куда звонить при ДТП."
    ),
    "apps": (
        "Вопрос о мобильных приложениях для оформления ДТП: "
        "Госуслуги.Авто, Помощник ОСАГО, ДТП.Европротокол — какое скачать, как использовать."
    ),
    "repair_ban": (
        "Вопрос о ремонте после ДТП: можно ли чинить, когда разрешат, нужно ли согласие страховой."
    ),
    "check_osago": (
        "Как проверить полис ОСАГО (свой или чужой): через сайт, приложение, действителен ли."
    ),
    "no_osago": (
        "Ситуация: у одного из участников ДТП нет страховки ОСАГО или она просрочена."
    ),
    "victims_injured": (
        "В ДТП есть пострадавшие: ранения, травмы, кровь, потеря сознания, сбил пешехода."
    ),
}

_PROMPT = """\
Определи намерение пользователя. Выбери ОДНУ категорию из списка или "none".

Категории:
{categories}

"none" — если запрос не подходит ни под одну категорию точно:
  - пользователь попал в ДТП и описывает ситуацию
  - просит помочь заполнить/оформить документы
  - задаёт конкретный вопрос по своей ситуации
  - всё, что требует анализа обстоятельств

Контекст диалога (последние сообщения):
{history}

Запрос пользователя:
{query}

Верни ТОЛЬКО валидный JSON без пояснений:
{{"category": "<ключ из списка или none>", "confidence": <число 0.0-1.0>}}
"""

# Минимальная уверенность для применения шаблона
_MIN_CONFIDENCE = 0.80


def llm_classify(
    giga: GigaChat,
    query: str,
    history_text: str = "",
) -> Optional[str]:
    """
    Классифицирует запрос и возвращает ключ шаблона или None.

    Args:
        giga: активный клиент GigaChat
        query: сообщение пользователя
        history_text: последние 2-3 реплики диалога (Q: ... A: ...)

    Returns:
        Ключ из TEMPLATES (например "greeting") или None.
    """
    categories_text = "\n".join(
        f'  "{key}": {desc}' for key, desc in _CATEGORIES.items()
    )

    prompt = _PROMPT.format(
        categories=categories_text,
        history=history_text or "(начало диалога)",
        query=query,
    )

    try:
        response = giga.chat(prompt)
        text = response.choices[0].message.content.strip()

        match = re.search(r"\{.*\}", text, re.DOTALL)
        if not match:
            return None

        data = json.loads(match.group(0))
        category = data.get("category", "none")
        confidence = float(data.get("confidence", 0.0))

        if category == "none" or confidence < _MIN_CONFIDENCE:
            return None

        # Проверяем, что ключ существует в наших шаблонах
        if category not in _CATEGORIES:
            return None

        return category

    except (json.JSONDecodeError, AttributeError, IndexError, ValueError, KeyError):
        return None