"""
Матчер шаблонных ответов — ТОЛЬКО строгий regex, без LLM.

Правило добавления паттерна:
  «Если эта фраза в контексте ДТП может означать что-то другое — не добавлять».

LLM-классификатор из этого модуля удалён намеренно:
  классификация намерений теперь живёт в agent/classifier.py
  как часть основного pipeline с полным контекстом диалога.
"""

from __future__ import annotations

import re
from typing import Optional

from templates.responses import TEMPLATES

# ---------------------------------------------------------------------------
# Строгие паттерны.
# Каждый паттерн должен быть «закрытым» (^ и $) или очень специфичным,
# чтобы не ловить случайные совпадения.
# ---------------------------------------------------------------------------
_STRICT_PATTERNS: dict[str, list[str]] = {

    # Чистое приветствие без каких-либо слов о ДТП
    "greeting": [
        r"^(привет|хай|хелло|hi|hello)[\s!.,]*$",
        r"^(добрый\s+(день|вечер|утро)|здравствуй(те)?|приветствую)[\s!.,]*$",
    ],

    # Явный запрос телефонов экстренных служб
    "emergency_numbers": [
        r"^(какой\s+номер|номер\s+телефона?)\s+(полиции|гибдд|скорой|мчс)[\s?!.]*$",
        r"^(куда|кому)\s+звонить(\s+при\s+(дтп|аварии|аварийной\s+ситуации))?[\s?!.]*$",
        r"^(телефон|номер)\s+(экстренных\s+служб|гибдд|скорой|мчс)[\s?!.]*$",
        r"^(дайте|скажите|напишите)\s+(номер|телефон)\s+(полиции|гибдд|скорой|мчс)[\s?!.]*$",
    ],

    # Однозначно есть пострадавшие — фраза без двойного толкования
    "victims_injured": [
        r"^есть\s+пострадавш(ий|ие|их)[\s.!]*$",
        r"^(человек|водитель|пассажир|пешеход)\s+(без\s+сознания|не\s+дышит|не\s+двигается)[\s.!]*$",
        r"^(ранен|тяжело\s+ранен|погиб)\s+(водитель|пассажир|пешеход)[\s.!]*$",
    ],

    # Явный вопрос о запрете ремонта — не «можно ли ехать», а именно ремонт
    "repair_ban": [
        r"^(можно\s+ли|когда\s+можно)\s+(ремонтировать|чинить|сдать\s+в\s+сервис)(\s+машину|\s+автомобиль)?[\s?!.]*$",
        r"^(через\s+сколько|когда)\s+(можно\s+)?(ремонт|в\s+сервис|починить)[\s?!.]*$",
        r"^запрет\s+на\s+ремонт[\s?!.]*$",
    ],
}


def match_template(query: str) -> Optional[str]:
    """
    Ищет шаблонный ответ только по строгим regex-паттернам.

    Args:
        query: сообщение пользователя (оригинал)

    Returns:
        Готовый текст ответа или None — передать дальше в pipeline.
    """
    q = query.strip().lower()

    for key, patterns in _STRICT_PATTERNS.items():
        for pattern in patterns:
            if re.search(pattern, q, re.IGNORECASE):
                return TEMPLATES[key]["response"]

    return None