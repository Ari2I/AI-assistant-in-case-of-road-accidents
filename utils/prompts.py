def build_state_card(
    current_step: str,
    scenario: str,
    known_facts: str,
    step_focus: str | None = None,
    step_blockers: str | None = None,
    required_next_question: str | None = None,
    is_terminal: bool = False,
    rag_context: str | None = None,
) -> str:
    """
    Строит STATE-карточку для передачи в системный промпт генератора.

    Args:
        current_step: текущий шаг диалога
        scenario: сценарий (standard, dispute_resolution, scheme_creation)
        known_facts: текстовая сводка известных фактов
        step_focus: что обсуждать на этом шаге (опционально, берётся из STEP_FOCUS)
        step_blockers: что запрещено упоминать (опционально, берётся из STEP_BLOCKERS)
        required_next_question: какой вопрос нужно задать (если ещё не задан)
        is_terminal: является ли шаг терминальным
        rag_context: контекст из RAG (кратко)

    Returns:
        formatted state card string
    """
    focus = step_focus or STEP_FOCUS.get(current_step, "")
    blockers = step_blockers or STEP_BLOCKERS.get(current_step, "")

    lines = [
        "=== STATE CARD ===",
        f"CURRENT_STEP: {current_step}",
        f"SCENARIO: {scenario}",
        f"IS_TERMINAL: {'yes' if is_terminal else 'no'}",
        "",
        "=== KNOWN FACTS ===",
        known_facts or "(факты ещё не собраны)",
        "",
        "=== STEP FOCUS ===",
        focus or "(нет специфичного фокуса)",
        "",
        "=== STEP BLOCKERS ===",
        blockers or "(нет специфичных ограничений)",
    ]

    if required_next_question:
        lines.extend([
            "",
            "=== REQUIRED NEXT QUESTION ===",
            required_next_question,
        ])

    if rag_context:
        # Краткая версия RAG контекста для state card
        rag_summary = rag_context[:500] + "..." if len(rag_context) > 500 else rag_context
        lines.extend([
            "",
            "=== RAG CONTEXT SUMMARY ===",
            rag_summary,
        ])

    lines.append("=== END STATE CARD ===")

    return "\n".join(lines)


def is_clarification_request(text: str) -> bool:
    """
    Детектирует запрос уточнения/повтора вопроса.

    Args:
        text: текст сообщения пользователя

    Returns:
        True если это запрос уточнения
    """
    text_lower = text.lower()

    clarification_markers = [
        "не понял", "не понимаю", "повтори", "ещё раз", "в смысле",
        "что ты спросил", "какой вопрос", "уточни", "объясни лучше",
        "не ясно", "непонятно", "заново", "сначала",
    ]

    return any(marker in text_lower for marker in clarification_markers)


