# Сколько чанков искать по каждому запросу категории
_K_PER_QUERY = 2

# Максимум уникальных чанков в итоговом контексте
_MAX_CHUNKS = 6

# Чанков из feedback DB (хорошие Q&A — приоритет)
_K_FEEDBACK = 2


def get_context_for_category(
    db,
    feedback_db,
    query: str,
    category: str,
) -> str:
    """
    Возвращает контекст из RAG, сфокусированный на категории запроса.

    Args:
        db: основная ChromaDB с документами
        feedback_db: база хороших Q&A (приоритет)
        query: исходный запрос пользователя
        category: ключ из CATEGORIES

    Returns:
        Строка контекста для передачи в LLM (чанки через разделитель).
    """
    seen: set[str] = set()
    chunks: list[str] = []

    def _add(docs) -> None:
        for d in docs:
            if len(chunks) >= _MAX_CHUNKS:
                return
            key = d.page_content[:120]
            if key not in seen:
                seen.add(key)
                chunks.append(d.page_content)

    # 1. Feedback DB — хорошие Q&A из реальных диалогов (высокий приоритет)
    if feedback_db:
        try:
            _add(feedback_db.similarity_search(query, k=_K_FEEDBACK))
        except Exception as e:
            print(f"[retriever] feedback_db error: {e}")

    # 2. Основная DB — по запросам категории
    if db:
        category_queries = _CATEGORY_QUERIES.get(category, [query])
        # Исходный запрос пользователя — первым (самый точный сигнал)
        all_queries = [query] + category_queries

        for q in all_queries:
            if len(chunks) >= _MAX_CHUNKS:
                break
            try:
                _add(db.similarity_search(q, k=_K_PER_QUERY))
            except Exception as e:
                print(f"[retriever] db error on query '{q[:40]}': {e}")

    if not chunks:
        return "Контекст недоступен — отвечай по алгоритму без ссылок на документы."

    return "\n\n---\n\n".join(chunks)