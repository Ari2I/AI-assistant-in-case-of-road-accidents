_DEFAULT_INSTRUCTIONS = (
    "- Отвечай по алгоритму, задавай уточняющие вопросы если ситуация неясна"
)


def generate_answer(
    giga: GigaChat,
    query: str,
    context: str,
    plan: dict,
    algorithm: str = "",
    history_text: str = "",
) -> str:
    """
    Генерирует ответ с учётом категории и адаптивной истории диалога.

    Args:
        giga:         активный клиент GigaChat
        query:        сообщение пользователя
        context:      контекст из RAG (отфильтрован по категории)
        plan:         словарь от meta_classifier (category, block)
        algorithm:    срез алгоритма для текущего блока
        history_text: отформатированная нумерованная история
    """
    category = plan.get("category", "first_steps")
    category_instructions = _CATEGORY_INSTRUCTIONS.get(category, _DEFAULT_INSTRUCTIONS)

    system_content = _BASE_SYSTEM.format(
        category=category,
        history_text=history_text or "(начало диалога)",
        algorithm=algorithm or "(алгоритм не загружен)",
        context=context,
        category_instructions=category_instructions,
    )

    payload = Chat(
        messages=[
            Messages(role=MessagesRole.SYSTEM, content=system_content),
            Messages(role=MessagesRole.USER, content=query),
        ],
        temperature=0.1,
    )

    response = giga.chat(payload)
    return response.choices[0].message.content