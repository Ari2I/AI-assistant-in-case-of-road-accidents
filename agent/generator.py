"""
Генератор ответов через GigaChat.

Изменения:
  - Системный промпт теперь адаптируется под категорию запроса
  - Алгоритм передаётся явно (ранее не передавался в core.py — баг исправлен)
  - Отдельные инструкции для каждой категории снижают галлюцинации
"""

from gigachat import GigaChat
from gigachat.models import Chat, Messages, MessagesRole

# Базовый системный промпт
_BASE_SYSTEM = """\
Ты — ДТП-ассистент. Помогаешь людям, попавшим в дорожно-транспортное происшествие.

КАТЕГОРИЯ ТЕКУЩЕГО ЗАПРОСА: {category}

=== ИСТОРИЯ ДИАЛОГА ===
{history_text}
=== КОНЕЦ ИСТОРИИ ===

=== АЛГОРИТМ ДИАЛОГА ===
{algorithm}
=== КОНЕЦ АЛГОРИТМА ===

=== КОНТЕКСТ ИЗ БАЗЫ ЗНАНИЙ ===
{context}
=== КОНЕЦ КОНТЕКСТА ===

ПРАВИЛА (обязательные):
1. Отвечай ТОЛЬКО на основе контекста и алгоритма. Не выдумывай суммы, сроки, статьи.
2. Если информации нет в контексте — скажи об этом прямо, не додумывай.
3. Держись текущей категории запроса. Не уходи в соседние темы без вопроса пользователя.
4. Используй историю диалога: не переспрашивай то, что пользователь уже сообщил.

ПРАВИЛА ДЛЯ КАТЕГОРИЙ:
{category_instructions}
"""

# Инструкции, специфичные для каждой категории
_CATEGORY_INSTRUCTIONS: dict[str, str] = {
    "first_steps": (
        "- Веди строго по алгоритму: Блоки 0 → 1 → 2 → 3\n"
        "- Задавай ОДИН вопрос за раз, жди ответа\n"
        "- При любых сомнениях в безопасности — сначала безопасность, потом документы\n"
        "- Не переходи к Европротоколу, пока не выяснены базовые условия"
    ),
    "europrotocol_possible": (
        "- Фокус: что делать на месте, как зафиксировать, какие приложения\n"
        "- Всегда уточни: есть ли приложение, есть ли разногласия\n"
        "- Называй конкретные лимиты (400/200/100 тыс.) только с привязкой к условиям\n"
        "- Напоминай о 60 минутах для передачи данных в РСА"
    ),
    "europrotocol_impossible": (
        "- Чётко объясни, ПОЧЕМУ Европротокол невозможен в данной ситуации\n"
        "- Дай конкретные инструкции: что делать до приезда ГИБДД\n"
        "- Напомни: не покидать место ДТП, зафиксировать всё на фото\n"
        "- Укажи нужные номера: 102 (полиция), 103 (скорая), 112 (единый)"
    ),
    "filling_europrotocol": (
        "- Отвечай на конкретный вопрос о заполнении, ссылайся на номер пункта\n"
        "- Если спрашивают о конкретном пункте — дай точную инструкцию по нему\n"
        "- Напоминай: пустые графы заполнять прочерком или буквой Z\n"
        "- Напоминай: исправления заверяются подписями обоих водителей"
    ),
    "insurance_communication": (
        "- Ссылайся на конкретные статьи закона и сроки из контекста\n"
        "- При вопросе о споре — направляй к финансовому уполномоченному (finombudsman.ru)\n"
        "- Уточни: потерпевший или виновник задаёт вопрос — ответы разные\n"
        "- Называй конкретные сроки: 5 рабочих дней, 15 календарных дней и т.д."
    ),
}

_DEFAULT_INSTRUCTIONS = (
    "- Отвечай по алгоритму, задавай уточняющие вопросы если ситуация неясна"
)


def generate_answer(
    giga: GigaChat,
    query: str,
    context: str,
    plan: dict,
    algorithm: str = "",
    history_text: str = "",
) -> str:
    """
    Генерирует ответ с учётом категории и адаптивной истории диалога.

    Args:
        giga: активный клиент GigaChat
        query: сообщение пользователя
        context: контекст из RAG (отфильтрован по категории)
        plan: словарь от planner (содержит category, stage, answer_type)
        algorithm: полный текст алгоритма (загружается в core.py один раз)
        history_text: отформатированная история (размер зависит от категории,
                      для filling_europrotocol — вся история + блок данных)

    Returns:
        Сгенерированный текст ответа.
    """
    category = plan.get("category", "first_steps")
    category_instructions = _CATEGORY_INSTRUCTIONS.get(category, _DEFAULT_INSTRUCTIONS)

    system_content = _BASE_SYSTEM.format(
        category=category,
        history_text=history_text or "(начало диалога)",
        algorithm=algorithm or "(алгоритм не загружен)",
        context=context,
        category_instructions=category_instructions,
    )

    payload = Chat(
        messages=[
            Messages(role=MessagesRole.SYSTEM, content=system_content),
            Messages(role=MessagesRole.USER, content=query),
        ],
        temperature=0.1,
    )

    response = giga.chat(payload)
    return response.choices[0].message.content